-- Comprehensive Survey Schema for Voxa Application
-- This script provides complete survey functionality including:
-- - Survey creation and management
-- - Question types (multiple choice, text, rating)
-- - Response collection and analysis
-- - Analytics and reporting
-- - Survey permissions and access control

-- Drop existing survey tables to recreate with comprehensive structure
DROP TABLE IF EXISTS answers CASCADE;
DROP TABLE IF EXISTS user_responses CASCADE;
DROP TABLE IF EXISTS questions CASCADE;
DROP TABLE IF EXISTS surveys CASCADE;

-- Main Surveys Table
CREATE TABLE surveys (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  description TEXT,
  created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status TEXT CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED', 'ARCHIVED')) DEFAULT 'DRAFT' NOT NULL,
  response_count INTEGER DEFAULT 0 NOT NULL,
  target_audience JSONB DEFAULT '[]'::jsonb, -- Array of roles, departments, or specific user IDs
  start_date TIMESTAMP WITH TIME ZONE,
  end_date TIMESTAMP WITH TIME ZONE,
  is_anonymous BOOLEAN DEFAULT FALSE NOT NULL,
  allow_multiple_responses BOOLEAN DEFAULT FALSE NOT NULL,
  require_authentication BOOLEAN DEFAULT TRUE NOT NULL,
  max_responses INTEGER, -- Maximum number of responses allowed
  survey_settings JSONB DEFAULT '{}'::jsonb, -- Additional settings like notifications, etc.
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Questions Table
CREATE TABLE questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  survey_id BIGINT NOT NULL REFERENCES surveys(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  type TEXT CHECK (type IN ('multiple_choice', 'checkbox', 'short_answer', 'long_answer', 'rating', 'date', 'time', 'email', 'number')) NOT NULL,
  "order" INTEGER NOT NULL,
  is_required BOOLEAN DEFAULT TRUE NOT NULL,
  options JSONB DEFAULT '[]'::jsonb, -- For multiple choice/checkbox questions
  validation_rules JSONB DEFAULT '{}'::jsonb, -- Validation rules for text inputs
  settings JSONB DEFAULT '{}'::jsonb, -- Additional question settings
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- User Responses Table (renamed from responses for clarity)
CREATE TABLE user_responses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  survey_id BIGINT NOT NULL REFERENCES surveys(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL, -- NULL for anonymous responses
  submitted_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  is_completed BOOLEAN DEFAULT FALSE NOT NULL,
  completion_time INTEGER, -- Time in seconds to complete the survey
  ip_address INET, -- For anonymous survey tracking
  user_agent TEXT, -- Browser/device info for analytics
  response_metadata JSONB DEFAULT '{}'::jsonb, -- Additional metadata
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  UNIQUE(survey_id, user_id) -- Prevent duplicate responses unless multiple responses allowed
);

-- Answers Table
CREATE TABLE answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  response_id BIGINT NOT NULL REFERENCES user_responses(id) ON DELETE CASCADE,
  question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  answer_text TEXT, -- For text-based answers
  answer_options JSONB DEFAULT '[]'::jsonb, -- For multiple choice/checkbox answers
  rating INTEGER CHECK (rating >= 1 AND rating <= 10), -- For rating questions (1-10 scale)
  numeric_value DECIMAL(15,2), -- For number questions
  date_value DATE, -- For date questions
  time_value TIME, -- For time questions
  email_value VARCHAR(255), -- For email questions
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Survey Analytics Table (for pre-computed analytics)
CREATE TABLE survey_analytics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  survey_id BIGINT NOT NULL REFERENCES surveys(id) ON DELETE CASCADE,
  question_id BIGINT REFERENCES questions(id) ON DELETE CASCADE,
  metric_type TEXT NOT NULL, -- 'response_rate', 'completion_rate', 'average_rating', etc.
  metric_value DECIMAL(15,4) NOT NULL,
  metric_data JSONB DEFAULT '{}'::jsonb, -- Additional metric data
  computed_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Survey Invitations Table (for targeted survey invitations)
CREATE TABLE survey_invitations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  survey_id BIGINT NOT NULL REFERENCES surveys(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  email VARCHAR(255), -- For external invitations
  invitation_token VARCHAR(255) UNIQUE,
  status TEXT CHECK (status IN ('pending', 'accepted', 'declined', 'expired')) DEFAULT 'pending',
  sent_at TIMESTAMP WITH TIME ZONE,
  responded_at TIMESTAMP WITH TIME ZONE,
  expires_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

