-- Function to increment response count
CREATE OR REPLACE FUNCTION increment_response_count(survey_id_param BIGINT)
RETURNS VOID AS $$
BEGIN
    UPDATE surveys 
    SET response_count = response_count + 1 
    WHERE id = survey_id_param;
END;
$$ LANGUAGE plpgsql;

-- Function to get survey analytics
CREATE OR REPLACE FUNCTION get_survey_analytics(survey_id_param BIGINT)
RETURNS TABLE (
  total_responses BIGINT,
  completed_responses BIGINT,
  completion_rate DECIMAL(5,2),
  average_completion_time INTEGER,
  responses_by_date DATE,
  response_count INTEGER
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        COUNT(DISTINCT ur.id) as total_responses,
        COUNT(DISTINCT CASE WHEN ur.is_completed = true THEN ur.id END) as completed_responses,
        CASE 
            WHEN COUNT(DISTINCT ur.id) > 0 THEN 
                ROUND((COUNT(DISTINCT CASE WHEN ur.is_completed = true THEN ur.id END) * 100.0 / COUNT(DISTINCT ur.id)), 2)
            ELSE 0 
        END as completion_rate,
        ROUND(AVG(ur.completion_time))::INTEGER as average_completion_time,
        DATE(ur.submitted_at) as responses_by_date,
        COUNT(ur.id) as response_count
    FROM user_responses ur
    WHERE ur.survey_id = survey_id_param
    GROUP BY DATE(ur.submitted_at)
    ORDER BY responses_by_date DESC;
END;
$$ LANGUAGE plpgsql;

-- Function to get question analytics
CREATE OR REPLACE FUNCTION get_question_analytics(question_id_param BIGINT)
RETURNS TABLE (
  total_answers BIGINT,
  answer_text TEXT,
  answer_options JSONB,
  rating INTEGER,
  answer_count INTEGER,
  answer_percentage DECIMAL(5,2)
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        COUNT(a.id) as total_answers,
        a.answer_text,
        a.answer_options,
        a.rating,
        COUNT(a.id) as answer_count,
        CASE 
            WHEN (SELECT COUNT(*) FROM answers WHERE question_id = question_id_param) > 0 THEN 
                ROUND((COUNT(a.id) * 100.0 / (SELECT COUNT(*) FROM answers WHERE question_id = question_id_param)), 2)
            ELSE 0 
        END as answer_percentage
    FROM answers a
    WHERE a.question_id = question_id_param
    GROUP BY a.answer_text, a.answer_options, a.rating;
END;
$$ LANGUAGE plpgsql;

