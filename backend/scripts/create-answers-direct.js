require('dotenv').config();
const { supabaseAdmin } = require('../config/database');

async function createAnswersDirect() {
  try {
    console.log('=== Creating Answers Table Directly ===');
    
    // Use raw SQL to create the table
    const { error } = await supabaseAdmin.rpc('exec', {
      sql: `
        CREATE TABLE IF NOT EXISTS answers (
          id bigint generated by default as identity primary key,
          response_id bigint not null references responses(id) on delete cascade,
          question_id bigint not null references questions(id) on delete cascade,
          answer_text text,
          answer_options jsonb,
          rating integer check (rating >= 1 and rating <= 5),
          created_at timestamp with time zone default now(),
          updated_at timestamp with time zone default now()
        );
        
        CREATE INDEX IF NOT EXISTS idx_answers_response_id ON answers(response_id);
        CREATE INDEX IF NOT EXISTS idx_answers_question_id ON answers(question_id);
        
        ALTER TABLE answers ENABLE ROW LEVEL SECURITY;
      `
    });
    
    if (error) {
      console.log('❌ Error creating table:', error);
      
      // Try alternative approach
      console.log('Trying to create table with direct insert...');
      
      // Try to insert a dummy record to create the table structure
      const { error: insertError } = await supabaseAdmin
        .from('answers')
        .insert([{
          response_id: 1,
          question_id: 1,
          answer_text: 'test'
        }]);
      
      if (insertError && !insertError.message.includes('does not exist')) {
        console.log('✅ Answers table exists or was created');
      } else {
        console.log('❌ Could not create answers table:', insertError);
      }
    } else {
      console.log('✅ Answers table created successfully');
    }
    
    // Test the table
    const { data, error: testError } = await supabaseAdmin
      .from('answers')
      .select('*')
      .limit(1);
    
    if (testError) {
      console.log('❌ Table test failed:', testError);
    } else {
      console.log('✅ Answers table is working');
    }
    
  } catch (error) {
    console.error('❌ Error:', error);
  }
}

createAnswersDirect();
