require('dotenv').config();
const { supabaseAdmin } = require('../config/database');

async function createPostsTable() {
  try {
    console.log('Creating posts table...');

    // Create posts table
    const { error: postsError } = await supabaseAdmin.rpc('execute_sql', {
      sql: `
        CREATE TABLE IF NOT EXISTS posts (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
          content TEXT NOT NULL,
          type VARCHAR(50) DEFAULT 'general',
          title TEXT,
          survey_id BIGINT,
          tags TEXT[] DEFAULT '{}',
          likes INTEGER DEFAULT 0,
          is_pinned BOOLEAN DEFAULT false,
          created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
          updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
        );
        
        CREATE INDEX IF NOT EXISTS idx_posts_user_id ON posts(user_id);
        CREATE INDEX IF NOT EXISTS idx_posts_created_at ON posts(created_at DESC);
        CREATE INDEX IF NOT EXISTS idx_posts_type ON posts(type);
      `
    });

    if (postsError) {
      console.error('Error creating posts table:', postsError);
    } else {
      console.log('✅ Posts table created successfully');
    }

    // Create comments table
    const { error: commentsError } = await supabaseAdmin.rpc('execute_sql', {
      sql: `
        CREATE TABLE IF NOT EXISTS comments (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          post_id BIGINT REFERENCES posts(id) ON DELETE CASCADE,
          user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
          content TEXT NOT NULL,
          parent_id BIGINT REFERENCES comments(id) ON DELETE CASCADE,
          created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
          updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
        );
        
        CREATE INDEX IF NOT EXISTS idx_comments_post_id ON comments(post_id);
        CREATE INDEX IF NOT EXISTS idx_comments_user_id ON comments(user_id);
        CREATE INDEX IF NOT EXISTS idx_comments_parent_id ON comments(parent_id);
      `
    });

    if (commentsError) {
      console.error('Error creating comments table:', commentsError);
    } else {
      console.log('✅ Comments table created successfully');
    }

    // Create likes table
    const { error: likesError } = await supabaseAdmin.rpc('execute_sql', {
      sql: `
        CREATE TABLE IF NOT EXISTS likes (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          post_id BIGINT REFERENCES posts(id) ON DELETE CASCADE,
          user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
          type VARCHAR(20) DEFAULT 'like',
          created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
          UNIQUE(post_id, user_id)
        );
        
        CREATE INDEX IF NOT EXISTS idx_likes_post_id ON likes(post_id);
        CREATE INDEX IF NOT EXISTS idx_likes_user_id ON likes(user_id);
      `
    });

    if (likesError) {
      console.error('Error creating likes table:', likesError);
    } else {
      console.log('✅ Likes table created successfully');
    }

    // Test the tables
    console.log('Testing tables...');
    
    // Test posts table
    const { data: postsTest, error: postsTestError } = await supabaseAdmin
      .from('posts')
      .select('count')
      .limit(1);
    
    if (postsTestError) {
      console.error('❌ Posts table test failed:', postsTestError);
    } else {
      console.log('✅ Posts table test passed');
    }

    // Test comments table
    const { data: commentsTest, error: commentsTestError } = await supabaseAdmin
      .from('comments')
      .select('count')
      .limit(1);
    
    if (commentsTestError) {
      console.error('❌ Comments table test failed:', commentsTestError);
    } else {
      console.log('✅ Comments table test passed');
    }

    // Test likes table
    const { data: likesTest, error: likesTestError } = await supabaseAdmin
      .from('likes')
      .select('count')
      .limit(1);
    
    if (likesTestError) {
      console.error('❌ Likes table test failed:', likesTestError);
    } else {
      console.log('✅ Likes table test passed');
    }

  } catch (error) {
    console.error('Error creating tables:', error);
  }
}

createPostsTable();
