require('dotenv').config();
const { supabaseAdmin } = require('../config/database');

async function createAnswersTable() {
  try {
    console.log('=== Creating Answers Table ===');
    
    // Check if table exists
    const { data: tables, error: checkError } = await supabaseAdmin
      .from('information_schema.tables')
      .select('table_name')
      .eq('table_schema', 'public')
      .eq('table_name', 'answers');
    
    if (checkError) {
      console.log('❌ Error checking table:', checkError);
      return;
    }
    
    if (tables && tables.length > 0) {
      console.log('✅ Answers table already exists');
      return;
    }
    
    // Create the answers table
    const { error: createError } = await supabaseAdmin.rpc('exec_sql', {
      sql: `
        CREATE TABLE answers (
          id bigint generated by default as identity primary key,
          response_id bigint not null references responses(id) on delete cascade,
          question_id bigint not null references questions(id) on delete cascade,
          answer_text text,
          answer_options jsonb,
          rating integer check (rating >= 1 and rating <= 5),
          created_at timestamp with time zone default now(),
          updated_at timestamp with time zone default now()
        );
        
        CREATE INDEX idx_answers_response_id ON answers(response_id);
        CREATE INDEX idx_answers_question_id ON answers(question_id);
        
        ALTER TABLE answers ENABLE ROW LEVEL SECURITY;
      `
    });
    
    if (createError) {
      console.log('❌ Error creating table:', createError);
      return;
    }
    
    console.log('✅ Answers table created successfully');
    
  } catch (error) {
    console.error('❌ Error:', error);
  }
}

createAnswersTable();
