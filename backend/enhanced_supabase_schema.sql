-- Create a view for dashboard access
CREATE VIEW user_dashboard_access AS
SELECT 
  u.id,
  u.first_name,
  u.last_name,
  u.email,
  u.role,
  u.last_login,
  CASE 
    WHEN u.role = 'student' THEN 'student_dashboard'
    WHEN u.role = 'faculty' THEN 'faculty_dashboard'
    WHEN u.role = 'admin' THEN 'admin_dashboard'
  END as dashboard_route,
  u.is_active
FROM users u
WHERE u.is_active = true;

