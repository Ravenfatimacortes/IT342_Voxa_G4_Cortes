-- Functions for role-based access control
CREATE OR REPLACE FUNCTION get_user_role(user_id_param BIGINT)
RETURNS TEXT AS $$
BEGIN
  RETURN (
    SELECT role FROM users 
    WHERE id = user_id_param AND is_active = true
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to check if user can access dashboard
CREATE OR REPLACE FUNCTION can_access_dashboard(user_id_param BIGINT, dashboard_type TEXT)
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM users 
    WHERE id = user_id_param 
    AND is_active = true
    AND (
      (dashboard_type = 'student' AND role = 'student') OR
      (dashboard_type = 'faculty' AND role = 'faculty') OR
      (dashboard_type = 'admin' AND role = 'admin')
    )
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

