-- Create basic RLS policies (you can customize these based on your app's requirements)

-- Users table policies
CREATE POLICY "Users can view own profile" ON users FOR SELECT USING (auth.uid()::text = id::text);
CREATE POLICY "Users can update own profile" ON users FOR UPDATE USING (auth.uid()::text = id::text);

-- Surveys table policies
CREATE POLICY "Surveys are viewable by everyone" ON surveys FOR SELECT USING (true);
CREATE POLICY "Authenticated users can create surveys" ON surveys FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Survey creators can update own surveys" ON surveys FOR UPDATE USING (created_by = auth.uid()::text);

-- Questions table policies
CREATE POLICY "Questions are viewable by everyone" ON questions FOR SELECT USING (true);
CREATE POLICY "Survey creators can manage questions" ON questions FOR ALL USING (
    EXISTS (SELECT 1 FROM surveys WHERE surveys.id = questions.survey_id AND surveys.created_by = auth.uid()::text)
);

-- Responses table policies
CREATE POLICY "Users can view own responses" ON responses FOR SELECT USING (user_id = auth.uid()::text);
CREATE POLICY "Users can create own responses" ON responses FOR INSERT WITH CHECK (user_id = auth.uid()::text);
CREATE POLICY "Users can update own responses" ON responses FOR UPDATE USING (user_id = auth.uid()::text);

-- Answers table policies
CREATE POLICY "Users can view own answers" ON answers FOR SELECT USING (
    EXISTS (SELECT 1 FROM responses WHERE responses.id = answers.response_id AND responses.user_id = auth.uid()::text)
);
CREATE POLICY "Users can create own answers" ON answers FOR INSERT WITH CHECK (
    EXISTS (SELECT 1 FROM responses WHERE responses.id = answers.response_id AND responses.user_id = auth.uid()::text)
);

-- Posts table policies
CREATE POLICY "Posts are viewable by everyone" ON posts FOR SELECT USING (true);
CREATE POLICY "Authenticated users can create posts" ON posts FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Users can update own posts" ON posts FOR UPDATE USING (user_id = auth.uid()::text);
CREATE POLICY "Users can delete own posts" ON posts FOR DELETE USING (user_id = auth.uid()::text);

-- Comments table policies
CREATE POLICY "Comments are viewable by everyone" ON comments FOR SELECT USING (true);
CREATE POLICY "Authenticated users can create comments" ON comments FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Users can update own comments" ON comments FOR UPDATE USING (user_id = auth.uid()::text);
CREATE POLICY "Users can delete own comments" ON comments FOR DELETE USING (user_id = auth.uid()::text);

-- Likes table policies
CREATE POLICY "Likes are viewable by everyone" ON likes FOR SELECT USING (true);
CREATE POLICY "Authenticated users can manage likes" ON likes FOR ALL USING (user_id = auth.uid()::text);
